CREATE DATABASE IF NOT EXISTS sannhaminh_new
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE sannhaminh_new;

CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, full_name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(30), password_hash VARCHAR(255) NOT NULL, role ENUM('PLAYER','OWNER','ADMIN') NOT NULL DEFAULT 'PLAYER',
 status ENUM('ACTIVE','LOCKED','DELETED') NOT NULL DEFAULT 'ACTIVE', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL UNIQUE, description VARCHAR(255), active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS venues (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT NOT NULL, category_id BIGINT, name VARCHAR(180) NOT NULL,
 description TEXT, address VARCHAR(255) NOT NULL, district VARCHAR(100), city VARCHAR(100) NOT NULL DEFAULT 'Hà Nội',
 image_url VARCHAR(500), price_per_hour DECIMAL(12,0) NOT NULL, amenities JSON NULL,
 status ENUM('PENDING','ACTIVE','REJECTED','ARCHIVED') NOT NULL DEFAULT 'PENDING', rating DECIMAL(3,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_venue_owner FOREIGN KEY(owner_id) REFERENCES accounts(id),
 CONSTRAINT fk_venue_category FOREIGN KEY(category_id) REFERENCES categories(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS venue_schedules (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, venue_id BIGINT NOT NULL, day_of_week TINYINT NOT NULL,
 open_time TIME NOT NULL, close_time TIME NOT NULL, slot_minutes INT NOT NULL DEFAULT 60, is_closed BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(venue_id) REFERENCES venues(id) ON DELETE CASCADE,
 UNIQUE KEY uq_venue_schedule_day(venue_id,day_of_week)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS bookings (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, booking_code VARCHAR(30) NOT NULL UNIQUE, player_id BIGINT NOT NULL, owner_id BIGINT NOT NULL,
 venue_id BIGINT NOT NULL, play_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
 total_hours INT NOT NULL, total_amount DECIMAL(12,0) NOT NULL, status ENUM('PENDING_OWNER','CONFIRMED','REJECTED','CANCELLED','COMPLETED') NOT NULL DEFAULT 'PENDING_OWNER',
 customer_note VARCHAR(500), owner_note VARCHAR(500), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(player_id) REFERENCES accounts(id), FOREIGN KEY(owner_id) REFERENCES accounts(id), FOREIGN KEY(venue_id) REFERENCES venues(id),
 INDEX idx_booking_slot(venue_id,play_date,start_time,end_time,status), INDEX idx_booking_player(player_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, booking_id BIGINT NOT NULL, payer_id BIGINT NOT NULL,
 method ENUM('BANK_TRANSFER','CASH','VNPAY','MOMO') NOT NULL, amount DECIMAL(12,0) NOT NULL,
 status ENUM('PENDING','PAID','REFUND_PENDING','REFUNDED','CANCELLED') NOT NULL DEFAULT 'PENDING',
 transaction_ref VARCHAR(120), proof_url VARCHAR(500), admin_note VARCHAR(500), confirmed_by BIGINT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(booking_id) REFERENCES bookings(id), FOREIGN KEY(payer_id) REFERENCES accounts(id), FOREIGN KEY(confirmed_by) REFERENCES accounts(id),
 UNIQUE KEY uq_payment_booking(booking_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, booking_id BIGINT NOT NULL, venue_id BIGINT NOT NULL, player_id BIGINT NOT NULL,
 rating TINYINT NOT NULL, content VARCHAR(1000), owner_reply VARCHAR(1000), status ENUM('VISIBLE','HIDDEN') NOT NULL DEFAULT 'VISIBLE', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(booking_id) REFERENCES bookings(id), FOREIGN KEY(venue_id) REFERENCES venues(id), FOREIGN KEY(player_id) REFERENCES accounts(id), UNIQUE KEY uq_review_booking(booking_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS favorites (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, player_id BIGINT NOT NULL, venue_id BIGINT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(player_id) REFERENCES accounts(id), FOREIGN KEY(venue_id) REFERENCES venues(id), UNIQUE KEY uq_favorite(player_id,venue_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, account_id BIGINT NOT NULL, title VARCHAR(180) NOT NULL, message VARCHAR(1000) NOT NULL,
 is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(account_id) REFERENCES accounts(id), INDEX idx_notification_account(account_id,is_read)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, actor_id BIGINT, action VARCHAR(120) NOT NULL, target_type VARCHAR(80), target_id BIGINT,
 details TEXT, ip_address VARCHAR(64), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor_id) REFERENCES accounts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
